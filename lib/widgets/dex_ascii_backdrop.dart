// The scene is landscape on purpose: about 16:10 once rendered in a
// monospace font, so it fills a desktop window instead of a phone column.
const int _gridCols = 150;
const int _gridRows = 50;
const int _lilyLeft = 56;
const int _lilyTop = 4;
const int _petals = 46;
const String _ramp = ' .:-=+*#%@';
const List<String> _petalGlyphs = ['`', ',', '.', '\'', '~', '*', '+'];

int _hash(int x, int y, int t) =>
    ((x * 73856093) ^ (y * 19349663) ^ (t * 83492791)) & 0x7fffffff;

/// One frame of the scene. Pure and deterministic so it can be tested.
String dexAsciiFrame(int tick) {
  final grid = List.generate(
    _gridRows,
    (_) => List<String>.filled(_gridCols, ' '),
  );

  // The lily sways a little, a row at a time, and the ink shimmers.
  for (var y = 0; y < _lilyRows; y++) {
    final sway = (math.sin(tick / 11 + y / 7) * 1.3).round();
    final row = _lily[y];
    for (var x = 0; x < _lilyCols; x++) {
      var level = row.codeUnitAt(x) - 48;
      if (level == 0) continue;
      final h = _hash(x, y, tick ~/ 3) % 13;
      if (h == 0) level -= 1;
      if (h == 1) level += 1;
      if (level < 1) continue;
      if (level > 9) level = 9;
      final gx = _lilyLeft + x + sway;
      if (gx < 0 || gx >= _gridCols) continue;
      grid[_lilyTop + y][gx] = _ramp[level];
    }
  }

  // Petals and ash drift down across the whole window.
  for (var i = 0; i < _petals; i++) {
    final speed = 1 + i % 3;
    final y = (i * 13 + tick * speed ~/ 3) % _gridRows;
    final sway = (math.sin(tick / 12 + i * 1.7) * 3).round();
    final x = ((i * 37 + 11) % _gridCols + sway) % _gridCols;
    if (grid[y][x] == ' ') grid[y][x] = _petalGlyphs[i % _petalGlyphs.length];
  }
  return grid.map((r) => r.join()).join('\n');
}

/// A faint, animated ASCII plate drawn over the whole app. It never takes
/// input, and it stops ticking when the system asks for reduced motion.
class DexAsciiBackdrop extends StatefulWidget {
  const DexAsciiBackdrop({super.key});

  @override
  State<DexAsciiBackdrop> createState() => _DexAsciiBackdropState();
}

class _DexAsciiBackdropState extends State<DexAsciiBackdrop> {
  final _tick = ValueNotifier<int>(0);
  Timer? _timer;

  @override
  void didChangeDependencies() {
    super.didChangeDependencies();
    _timer?.cancel();
    if (!MediaQuery.disableAnimationsOf(context)) {
      _timer = Timer.periodic(
        const Duration(milliseconds: 150),
        (_) => _tick.value++,
      );
    }
  }

  @override
  void dispose() {
    _timer?.cancel();
    _tick.dispose();
    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    final dark = Theme.of(context).brightness == Brightness.dark;
    final color = (dark ? const Color(0xFFF2F2F2) : const Color(0xFF0A0A0A))
        .withValues(alpha: dark ? 0.15 : 0.12);
    return RepaintBoundary(
      child: FittedBox(
        fit: BoxFit.contain,
        child: ValueListenableBuilder<int>(
          valueListenable: _tick,
          builder: (context, tick, _) => Text(
            dexAsciiFrame(tick),
            style: TextStyle(
              fontFamily: 'Consolas',
              fontFamilyFallback: const [
                'Cascadia Mono',
                'Courier New',
                'monospace',
              ],
              fontSize: 14,
              height: 1.0,
              color: color,
              decoration: TextDecoration.none,
            ),
          ),
        ),
      ),
    );
  }
}
